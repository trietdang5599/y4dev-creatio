define("MjmlContentExporter", ["MjmlCore", "MjmlContentExporterResources", "ContentBuilderConfigToMjmlConverter",
		"ContentBuilderConstants"],
	function (mjml) {
		/**
		 * @class Terrasoft.configuration.MjmlContentExporter
		 */
		Ext.define("Terrasoft.configuration.MjmlContentExporter", {
			extend: "Terrasoft.BaseContentExporter",
			alternateClassName: "Terrasoft.MjmlContentExporter",

			/**
			 * Default minification config.
			 * @protected
			 * @type {Object}
			 */
			minificationConfig: {
				collapseBooleanAttributes: true,
				collapseWhitespace: false,
				collapseInlineTagWhitespace: true,
				keepClosingSlash: true,
				html5: false,
				minifyCSS: true,
				removeComments: true,
				removeEmptyAttributes: true,
				removeRedundantAttributes: true,
				caseSensitive: true,
				removeAttributeQuotes: false
			},

			/** Type of exported item.
			 * @protected
			 * @type {Object}
			 */
			ExportedItemType: _.assign({}, Terrasoft.ExportedItemType, {
				HTML: Terrasoft.ContentBuilderBodyItemType.mjraw.value,
				BLOCK: Terrasoft.ContentBuilderBodyItemType.mjblock.value,
				SECTION: Terrasoft.ContentBuilderBodyItemType.section.value,
				COLUMN: Terrasoft.ContentBuilderBodyItemType.column.value
			}),

			/**
			 * Returns converter for content builder config to Mjml config.
			 * @protected
			 * @returns {Terrasoft.converters.ContentBuilderConfigToMjmlConverter}
			 * Content builder template config to MJML config converter.
			 */
			getContentBuilderToMjmlConverter: function() {
				return new Terrasoft.ContentBuilderConfigToMjmlConverter();
			},

			/**
			 * Applies left alignment to HTML body content.
			 * Only modifies top-level containers (mj-block, mj-block-outlook) and their immediate child tables.
			 * Nested tables and inner content alignment remain unchanged.
			 * @private
			 * @param {String} html HTML string generated by MJML.
			 * @returns {String} Modified HTML with left alignment.
			 */
			_applyLeftAlignment: function(html) {
				html = html.replace(
					/(class="mj-block"[^>]*style="[^"]*?)margin:\s*0px\s+auto\s*;/gi,
					'$1margin: 0;'
				);
				html = html.replace(
					/(<table[^>]*class="mj-block-outlook"[^>]*)\s+align="center"/gi,
					'$1 align="left"'
				);
				return html;
			},

			/**
			 * Applies right alignment to HTML body content.
			 * Only modifies top-level containers (mj-block, mj-block-outlook) and their immediate child tables.
			 * Nested tables and inner content alignment remain unchanged.
			 * @private
			 * @param {String} html HTML string generated by MJML.
			 * @returns {String} Modified HTML with right alignment.
			 */
			_applyRightAlignment: function(html) {
				// Replace margin: 0px auto on divs with class="mj-block" only
				html = html.replace(
					/(class="mj-block"[^>]*style="[^"]*?)margin:\s*0px\s+auto\s*;/gi,
					'$1margin: 0 0 0 auto;'
				);
				html = html.replace(
					/(<table[^>]*class="mj-block-outlook"[^>]*)\s+align="center"/gi,
					'$1 align="right"'
				);

				return html;
			},

			/**
			 * Transforms HTML to align body content to left, center, or right.
			 * Center alignment is the default MJML behavior and requires no transformation.
			 * @private
			 * @param {String} html Generated HTML from MJML.
			 * @param {String} align Alignment value ('left', 'center', 'right').
			 * @returns {String} Transformed HTML.
			 */
			_transformHtmlAlignment: function(html, align) {
				if (!align || align === 'center') {
					return html;
				}
				if (align === 'left') {
					return this._applyLeftAlignment(html);
				}
				if (align === 'right') {
					return this._applyRightAlignment(html);
				}
				return html;
			},

			/**
			 * Exports content builder template config to html.
			 * @public
			 * @param config Content builder template config.
			 * @returns {String} Html text.
			 */
			exportData: function(config) {
				var converter = this.getContentBuilderToMjmlConverter();
				var mjmlConfig = converter.convert(config);
				var isMinificationEnabled = Terrasoft.Features.getIsEnabled("MinifyEmailHtml");
				var mjmlResult = isMinificationEnabled
					? mjml(mjmlConfig, { minify: this.minificationConfig })
					: mjml(mjmlConfig);
				var align = config.SheetAlign || 'center';
				var transformedHtml = this._transformHtmlAlignment(mjmlResult.html, align);
				var sanitizedHtml = Terrasoft.sanitizeHTML(transformedHtml,
					Terrasoft.sanitizationLevel.HTML);
				return sanitizedHtml;
			}
		});
	}
);
